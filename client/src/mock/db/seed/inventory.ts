export function seedConsumables(now: number): Consumable[] {
  return CONSUMABLES.map((c) => {
    const { expiresInDays, ...rest } = c
    const consumable: Consumable = {
      ...rest,
      transactions: [
        {
          id: `${c.id}_use`,
          at: now - 1 * HOUR,
          by: 'st_shruthi',
          type: 'consume',
          quantity: -c.dailyUsage * 6,
          balance: c.quantity,
          note: 'Issued to collection and benches.',
        },
        {
          id: `${c.id}_rcv`,
          at: now - 12 * DAY,
          by: 'st_ganesh',
          type: 'receive',
          quantity: c.quantity + c.dailyUsage * 6,
          balance: c.quantity + c.dailyUsage * 6,
          note: 'Monthly indent received.',
        },
      ],
    }
    if (expiresInDays !== undefined)
      consumable.expiresAt = now + expiresInDays * DAY
    return consumable
  })
}
