export function seedEquipment(now: number): Equipment[] {
  return EQUIPMENT_SEEDS.map((s, i) => {
    const log: Equipment['log'] = [
      {
        id: `eql_${s.id}_m`,
        at: now - s.maint[0] * DAY,
        by: 'st_ganesh',
        type: 'maintenance',
        note: 'Preventive maintenance completed as per schedule.',
      },
      {
        id: `eql_${s.id}_c`,
        at: now - s.calib[0] * DAY,
        by: 'st_ganesh',
        type: 'calibration',
        note: 'Calibration verified with manufacturer calibrators.',
      },
    ]
    if (s.note)
      log.push({
        id: `eql_${s.id}_s`,
        at: now - (s.status === 'out-of-service' ? 20 * HOUR : 3 * HOUR),
        by: 'st_prakash',
        type: s.status === 'out-of-service' ? 'breakdown' : 'status-change',
        note: s.note,
        status: s.status,
      })
    return {
      id: s.id,
      name: s.name,
      model: s.model,
      manufacturer: s.manufacturer,
      serialNo: `${s.manufacturer.slice(0, 2).toUpperCase()}${(41870 + i * 373).toString()}`,
      department: s.department,
      status: s.status,
      location: s.location,
      lastMaintenanceAt: now - s.maint[0] * DAY,
      nextMaintenanceAt: now + s.maint[1] * DAY,
      lastCalibrationAt: now - s.calib[0] * DAY,
      calibrationDueAt: now + s.calib[1] * DAY,
      capacityPerHour: s.capacityPerHour,
      testIds: s.testIds,
      log: log.toSorted((a, b) => b.at - a.at),
    }
  })
}

