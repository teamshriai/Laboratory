export function seedReagents(now: number): {
  reagents: Reagent[]
  lots: ReagentLot[]
} {
  const reagents: Reagent[] = []
  const lots: ReagentLot[] = []
  for (const s of REAGENT_SEEDS) {
    const { lots: lotSeeds, ...reagent } = s
    reagents.push(reagent)
    lotSeeds.forEach(
      (
        [
          lotNumber,
          quantity,
          initial,
          receivedDays,
          expiresDays,
          qcStatus,
          state,
        ],
        i,
      ) => {
        const receivedAt = now - receivedDays * DAY
        const id = `lot_${s.id}_${i}`
        const transactions: ReagentLot['transactions'] = [
          {
            id: `${id}_rcv`,
            at: receivedAt,
            by: 'st_ganesh',
            type: 'receive',
            quantity: initial,
            balance: initial,
            note: 'Received against purchase order.',
          },
        ]
        if (quantity < initial)
          transactions.push({
            id: `${id}_use`,
            at: now - 2 * HOUR,
            by: 'st_prakash',
            type: 'consume',
            quantity: quantity - initial,
            balance: quantity,
            note: 'Consumed in routine testing.',
          })
        if (state === 'quarantined')
          transactions.push({
            id: `${id}_q`,
            at: now - 5 * HOUR,
            by: 'st_lavanya',
            type: 'quarantine',
            quantity: 0,
            balance: quantity,
            note: 'New lot failed acceptance QC (L2 above 3 SD). Held pending vendor review.',
          })
        lots.push({
          id,
          reagentId: s.id,
          lotNumber,
          receivedAt,
          expiresAt: now + expiresDays * DAY,
          quantity,
          initialQuantity: initial,
          qcStatus,
          state: state ?? 'active',
          transactions: transactions.toSorted((a, b) => b.at - a.at),
        })
      },
    )
  }
  return { reagents, lots }
}

